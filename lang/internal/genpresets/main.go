// Command genpresets writes presets_gen.go: the presets of the synths of psalm, by name. A preset is a function of the package of the synth
// without arguments that gives its Config (modal.Marimba(), piano.GrandPreset()); its name in a patch is the name of the function in snake
// case, without Preset. Run it from lang/ when psalm has new presets:
//
//	go run ./internal/genpresets > presets_gen.go
package main

import (
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"unicode"
)

// synths are the packages to take presets from, and the name of the table they make
var synths = []string{"modal", "piano", "waveguide", "vocal", "pulsar", "shaper"}

func main() {
	root := "../../psalm/synths"
	if len(os.Args) > 1 {
		root = os.Args[1]
	}
	fmt.Println("// Code generated by internal/genpresets; DO NOT EDIT.")
	fmt.Println()
	fmt.Println("package lang")
	fmt.Println()
	fmt.Println("import (")
	for _, s := range synths {
		fmt.Printf("\t\"github.com/almerlucke/psalm/synths/%s\"\n", s)
	}
	fmt.Println(")")
	for _, s := range synths {
		names := presets(filepath.Join(root, s))
		fmt.Printf("\nvar %sPresets = map[string]func() %s.Config{\n", s, s)
		for _, n := range names {
			fmt.Printf("\t%q: %s.%s,\n", snake(strings.TrimSuffix(n, "Preset")), s, n)
		}
		fmt.Println("}")
	}
}

// presets are the functions of a package that take nothing and give its Config
func presets(dir string) []string {
	fset := token.NewFileSet()
	pkgs, err := parser.ParseDir(fset, dir, func(fi os.FileInfo) bool { return !strings.HasSuffix(fi.Name(), "_test.go") }, 0)
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	var names []string
	for _, pkg := range pkgs {
		for _, f := range pkg.Files {
			for _, d := range f.Decls {
				fn, ok := d.(*ast.FuncDecl)
				if !ok || fn.Recv != nil || !fn.Name.IsExported() || fn.Name.Name == "DefaultConfig" {
					continue
				}
				if len(fn.Type.Params.List) != 0 || fn.Type.Results == nil || len(fn.Type.Results.List) != 1 {
					continue
				}
				if id, ok := fn.Type.Results.List[0].Type.(*ast.Ident); ok && id.Name == "Config" {
					names = append(names, fn.Name.Name)
				}
			}
		}
	}
	sort.Strings(names)
	return names
}

// snake turns GrandPiano into grand_piano (and PWMPad into pwm_pad, FMBass into fm_bass, Bass808 into bass808)
func snake(s string) string {
	rs := []rune(s)
	var b strings.Builder
	for i, r := range rs {
		if unicode.IsUpper(r) && i > 0 {
			prev := rs[i-1]
			nextLower := i+1 < len(rs) && unicode.IsLower(rs[i+1])
			if unicode.IsLower(prev) || unicode.IsDigit(prev) && false || (unicode.IsUpper(prev) && nextLower) {
				b.WriteByte('_')
			}
		}
		b.WriteRune(unicode.ToLower(r))
	}
	return b.String()
}
